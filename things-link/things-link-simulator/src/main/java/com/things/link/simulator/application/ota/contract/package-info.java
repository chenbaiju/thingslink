/**
 * 设备侧 OTA 线合同（S13-4d-2a）：Topic 常量、规范编解码与传输端口。
 *
 * <h2>本片交付什么</h2>
 * <p>把设备真正会发出/收到的 OTA 报文按平台的冻结格式写死成可独立测试的编解码器，并提供
 * 一个只搬运字节的传输端口。交付目标是「线格式可证明一致」：测试用 test scope 引入平台
 * OTA 模块，把同一组值分别交给设备侧编码器与平台编解码器，断言规范字节逐字节相同。</p>
 *
 * <h2>本片刻意不做什么（为什么）</h2>
 * <ul>
 *   <li><b>不依赖 OTA 模块。</b>跨模块只能引用对方 {@code application} 包，而且设备侧合同必须
 *       能在没有平台进程的现场独立解析；因此本包自带受限规范 JSON 与字段校验，只靠 JDK 与
 *       {@code things-link-shared}。</li>
 *   <li><b>不验签、不裁决安全事实。</b>下载响应里的签名与清单只被原样保留；健康/自检/进度的
 *       布尔声明完全由调用方提供，本包不替设备编造。</li>
 *   <li><b>不声称派发。</b>真正的 OTA 派发需要受控签名器签出 READY 固件；模拟器不持有私钥，
 *       因此本包不产生任何「平台已派发」的事实，只保证设备发出的字节与平台合同一致。</li>
 * </ul>
 *
 * <p>解码器要求输入已经是规范字节（比平台解码器更严格），理由是规范字节同时是摘要与签名的
 * 输入，接受乱序/空白等价输入会让同一事实存在多种可签名字节。</p>
 */
