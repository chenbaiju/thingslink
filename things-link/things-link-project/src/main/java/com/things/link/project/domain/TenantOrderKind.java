package com.things.link.project.domain;

/**
 * 订单种类（S14-3b；S14-4a 增加资源包购买）。
 *
 * <p>{@link #PURCHASE} 是 S14-3a 的整份购买/续费：金额取修订版参考价，服务期按 P5
 * 「首购 now → now + 周期、续费从上一 ends_at 延长」计算。{@link #UPGRADE} 是升级：金额取
 * 按整日折算的补差，服务期起点是报价时刻、终点保持原服务期终点不变。{@link #PACKAGE} 是
 * 资源包购买（S14-4a）：不承载产品修订版，金额取包维度的每单位参考价基准，生效后写入一条
 * 独立有效期的资源包事实，**不改订阅、不改服务期**。
 *
 * <p>种类决定支付成功事件走哪条生效分支，因此它是订单行的显式快照，而不是靠
 * 「金额是否等于参考价」推断：0 补差的升级金额与免费档的 0 元无法靠金额区分。
 */
public enum TenantOrderKind {

    /** 整份购买或续费（S14-3a）。 */
    PURCHASE,

    /** 升级补差，立即生效且不改动已付服务期终点（S14-3b）。 */
    UPGRADE,

    /** 资源包购买，生效为独立 starts_at/ends_at 的扩容权益（S14-4a）。 */
    PACKAGE
}
