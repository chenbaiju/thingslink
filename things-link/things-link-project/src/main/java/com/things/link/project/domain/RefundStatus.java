package com.things.link.project.domain;

/**
 * 退款状态（S14-5a；取值与 {@code sys_tenant_refund_status_ck} 逐字一致）。
 *
 * <p>本片只写入 {@link #SUCCEEDED}：负责人已确认支付功能暂不开发，模拟渠道的退款申请即视为成功，
 * 因此不存在「处理中」这个中间态——写一个永远不前进的 PENDING 只会让对账口径凭空多出一个悬空状态。
 * {@link #FAILED} 是真实渠道落地时的预留取值（渠道可能拒退），本片不写、也不发明它的补偿语义。
 *
 * <p>失败/重复的渠道回调不写本表：它们不是退款事实，而与支付失败一样只应留下可幂等的失败事实
 * （S14-5b），否则「退过一次」与「退失败过一次」会在同一张表里互相冒充。
 */
public enum RefundStatus {

    /** 退款已成功：资金已退出，来源权益按同步规则收回。 */
    SUCCEEDED,

    /** 退款失败（预留，真实渠道落地时写入；本片不写）。 */
    FAILED
}
